def planet_floor(path):
    """Podłoga Shiptesta z przyrostkiem planety -> nasza podłoga i edycja atmosfery."""
    parts = path.split('/')
    gas = None
    interior = False
    kept = []
    for part in parts:
        if part in PLANET_SUFFIX:
            gas = PLANET_SUFFIX[part]
        elif part == 'lit':
            continue
        elif part == 'interior':
            interior = True
        else:
            kept.append(part)
    base = '/'.join(kept)
    target = FLOOR_BASE.get(base)
    if target is None:
        raise KeyError('brak podłogi bazowej dla ' + path)
    if not gas:
        return target
    edits = {'initial_gas_mix': gas}
    if not interior:
        edits['planetary_atmos'] = '1'
    return (target, edits)



import { sortBy } from 'es-toolkit';
import type { ReactNode } from 'react';
import {
  Dimmer,
  Icon,
  Section,
  Stack,
  VirtualList,
} from 'tgui-core/components';
import { classes } from 'tgui-core/react';

import { useSharedState } from '../../backend';
import { SearchBar } from '../common/SearchBar';
import type { Design, MaterialMap } from './Types';

/**
 * A meta-category that, when selected, renders all designs to the output.
 */
const ALL_CATEGORY = 'All Designs';

/**
 * A meta-category that collects all designs without a single category.
 */
const UNCATEGORIZED = '/Uncategorized';

/** Category titles generated here rather than sent by the server. */
const CATEGORY_TITLES: Record<string, string> = {
  [ALL_CATEGORY]: 'Wszystkie projekty',
  Uncategorized: 'Bez kategorii',
};

const categoryTitle = (title: string) => CATEGORY_TITLES[title] ?? title;

/**
 * Categories present in this object are not rendered to the final fabricator
 * UI.
 */
const BLACKLISTED_CATEGORIES: Record<string, boolean> = {
  initial: true,
  core: true,
  hacked: true,
  emagged: true, // AQUILA: our lathes also tag designs unlocked by an emag
};

/**
 * A single category in the category tree.
 */
export type Category<T extends Design = Design> = {
  /** The human-readable title of this category. */
  title: string;
  /** The `id` of the element rendering this category, for the sidebar tabs. */
  anchorKey: string;
  /**
   * Every design in this category and its descendants, keyed by design id.
   */
  descendants: Record<string, T>;
  /** All designs within this specific category. */
  children: T[];
  /** The subcategories within this one, keyed by their titles. */
  subcategories: Record<string, Category<T>>;
};

export type DesignBrowserProps<T extends Design = Design> = {
  /** All of the designs available to the browser. */
  designs: T[];
  /** A map of materials available for printing designs. */
  availableMaterials?: MaterialMap;
  /** If present, dims out the recipe list with a "building items" animation. */
  busy?: boolean;
  /**
   * Invoked for every recipe visible in the design browser. Returns a single
   * row to be rendered to the output.
   */
  buildRecipeElement: (design: T, availableMaterials: MaterialMap) => ReactNode;
  /** If provided, renders a node into each category in the output. */
  categoryButtons?: (category: Category<T>) => ReactNode;
};

const makeCategory = <T extends Design>(
  title: string,
  anchorKey: string,
): Category<T> => ({
  title,
  anchorKey,
  descendants: {},
  children: [],
  subcategories: {},
});

/**
 * A universal design browser. Takes an arbitrary array of designs, and
 * generates tabs, a search bar, and a list of designs. Each row of the
 * resulting table is generated by the provided `buildRecipeElement` function.
 */
export const DesignBrowser = <T extends Design = Design>(
  props: DesignBrowserProps<T>,
) => {
  const {
    designs,
    availableMaterials,
    buildRecipeElement,
    busy,
    categoryButtons,
  } = props;

  const [selectedCategory, setSelectedCategory] = useSharedState(
    'selected_category',
    ALL_CATEGORY,
  );

  const [searchText, setSearchText] = useSharedState('search_text', '');

  const onCategorySelected = (newCategory: string) => {
    if (newCategory === selectedCategory) {
      return;
    }

    setSelectedCategory(newCategory);
    setSearchText('');
  };

  // Build a root category from the designs.
  const root = makeCategory<T>(ALL_CATEGORY, ALL_CATEGORY.replace(/ /g, ''));

  // Sort every design into a single category in the tree.
  for (const design of designs) {
    const categories = design.categories.length
      ? design.categories
      : [UNCATEGORIZED];

    for (const category of categories) {
      // If the category is a blacklisted meta-category, skip it entirely.
      if (BLACKLISTED_CATEGORIES[category]) {
        continue;
      }

      // Categories are slash-delimited, a leading slash gives an empty group.
      const nodes = category.split('/').filter((node) => node.length > 0);

      let parent = root;
      // AQUILA: anchors carry the whole path, so two subcategories of the same name don't collide.
      let path = '';

      for (const node of nodes) {
        parent.descendants[design.id] = design;
        path += `/${node}`;
        parent.subcategories[node] ||= makeCategory<T>(
          node,
          path.replace(/ /g, ''),
        );
        parent = parent.subcategories[node];
      }

      // This is our leaf.
      parent.descendants[design.id] = design;
      parent.children.push(design);
    }
  }

  const allDesigns = sortBy(Object.values(root.descendants), [
    (design: T) => design.name,
  ]);

  const renderDesign = (design: T) => (
    <div key={design.id}>
      {buildRecipeElement(design, availableMaterials || {})}
    </div>
  );

  return (
    <Stack fill>
      {/* Left Column */}
      <Stack.Item width="200px">
        <Section fill>
          <Stack vertical fill>
            <Stack.Item>
              <Section title="Kategorie" fitted />
            </Stack.Item>
            <Stack.Item grow style={{ overflowY: 'auto', overflowX: 'hidden' }}>
              <Section fill>
                <div className="FabricatorTabs">
                  <div
                    className={classes([
                      'FabricatorTabs__Tab',
                      selectedCategory === ALL_CATEGORY &&
                        'FabricatorTabs__Tab--active',
                    ])}
                    onClick={() => onCategorySelected(ALL_CATEGORY)}
                  >
                    <div className="FabricatorTabs__Label">
                      <div className="FabricatorTabs__CategoryName">
                        {categoryTitle(ALL_CATEGORY)}
                      </div>
                      <div className="FabricatorTabs__CategoryCount">
                        ({Object.keys(root.descendants).length})
                      </div>
                    </div>
                  </div>

                  {sortBy(Object.values(root.subcategories), [
                    (category: Category<T>) => category.title,
                  ]).map((category) => (
                    <DesignBrowserTab
                      key={category.title}
                      category={category}
                      selectedCategory={selectedCategory}
                      setSelectedCategory={onCategorySelected}
                    />
                  ))}
                </div>
              </Section>
            </Stack.Item>
          </Stack>
        </Section>
      </Stack.Item>

      {/* Right Column */}
      <Stack.Item grow>
        <Section
          title={
            searchText.length > 0
              ? `Wyniki dla „${searchText}”`
              : categoryTitle(selectedCategory)
          }
          fill
        >
          <Stack vertical fill>
            <Stack.Item>
              <Section>
                <SearchBar
                  expensive
                  query={searchText}
                  onSearch={setSearchText}
                  placeholder="Szukaj we wszystkich projektach..."
                />
              </Section>
            </Stack.Item>
            <Stack.Item grow style={{ overflowY: 'auto', overflowX: 'hidden' }}>
              <Section fill>
                {searchText.length > 0 ? (
                  <VirtualList>
                    {allDesigns
                      .filter((design) =>
                        design.name
                          .toLowerCase()
                          .includes(searchText.toLowerCase()),
                      )
                      .map(renderDesign)}
                  </VirtualList>
                ) : selectedCategory === ALL_CATEGORY ? (
                  <VirtualList>{allDesigns.map(renderDesign)}</VirtualList>
                ) : (
                  root.subcategories[selectedCategory] && (
                    <CategoryView
                      category={root.subcategories[selectedCategory]}
                      categoryButtons={categoryButtons}
                      availableMaterials={availableMaterials}
                      buildRecipeElement={buildRecipeElement}
                    />
                  )
                )}
              </Section>
            </Stack.Item>
            {!!busy && (
              <Dimmer
                style={{
                  fontSize: '2em',
                  textAlign: 'center',
                }}
              >
                <Icon name="cog" spin />
                {' Trwa produkcja...'}
              </Dimmer>
            )}
          </Stack>
        </Section>
      </Stack.Item>
    </Stack>
  );
};

type DesignBrowserTabProps<T extends Design = Design> = {
  category: Category<T>;
  depth?: number;
  maxDepth?: number;
  selectedCategory: string;
  setSelectedCategory: (newCategory: string) => void;
};

const DesignBrowserTab = <T extends Design = Design>(
  props: DesignBrowserTabProps<T>,
) => {
  const { category, selectedCategory, setSelectedCategory } = props;
  const depth = props.depth ?? 0;
  const maxDepth = props.maxDepth ?? 3;
  const topLevel = depth === 0;

  return (
    <div
      className={classes([
        'FabricatorTabs__Tab',
        /** Only highlight top-level categories. */
        topLevel &&
          selectedCategory === category.title &&
          'FabricatorTabs__Tab--active',
      ])}
      onClick={(event) => {
        // A nested tab sits inside its parent's tab, which would otherwise take the click too.
        event.stopPropagation();
        if (topLevel) {
          // For top-level categories, set the selected category.
          setSelectedCategory(category.title);
        } else {
          // For deeper categories, scroll the subcategory header into view.
          document.getElementById(category.anchorKey)?.scrollIntoView(true);
        }
      }}
    >
      <div className="FabricatorTabs__Label">
        <div className="FabricatorTabs__CategoryName">
          {categoryTitle(category.title)}
        </div>
        {topLevel && (
          /** Show recipe counts on top-level categories. */
          <div className="FabricatorTabs__CategoryCount">
            ({Object.keys(category.descendants).length})
          </div>
        )}
      </div>
      {depth < maxDepth &&
        Object.keys(category.subcategories).length > 0 &&
        selectedCategory === category.title && (
          <div className="FabricatorTabs">
            {sortBy(Object.values(category.subcategories), [
              (subcategory: Category<T>) => subcategory.title,
            ]).map((subcategory) => (
              <DesignBrowserTab
                key={subcategory.title}
                category={subcategory}
                depth={depth + 1}
                maxDepth={maxDepth}
                selectedCategory={selectedCategory}
                setSelectedCategory={setSelectedCategory}
              />
            ))}
          </div>
        )}
    </div>
  );
};

type CategoryViewProps<T extends Design = Design> = {
  /** The category being rendered. */
  category: Category<T>;
  /** A map of materials available for printing designs. */
  availableMaterials?: MaterialMap;
  /** The depth of this category in the view. */
  depth?: number;
  buildRecipeElement: (design: T, availableMaterials: MaterialMap) => ReactNode;
  /** If provided, renders a node into each category in the output. */
  categoryButtons?: (category: Category<T>) => ReactNode;
};

const CategoryView = <T extends Design = Design>(
  props: CategoryViewProps<T>,
) => {
  const { category, availableMaterials, buildRecipeElement, categoryButtons } =
    props;
  const depth = props.depth ?? 0;

  const body = (
    <>
      {sortBy(category.children, [(design: T) => design.name]).map((design) => (
        <div key={design.id}>
          {buildRecipeElement(design, availableMaterials || {})}
        </div>
      ))}
      {sortBy(Object.values(category.subcategories), [
        (subcategory: Category<T>) => subcategory.title,
      ]).map((subcategory) => (
        <CategoryView
          {...props}
          key={subcategory.anchorKey}
          category={subcategory}
          depth={depth + 1}
        />
      ))}
    </>
  );

  if (depth === 0) {
    return body;
  }

  // AQUILA: a category whose designs all sit in subcategories gets no header
  // of its own, but it still carries the anchor its sidebar tab scrolls to.
  if (category.children.length === 0) {
    return (
      <div className="Fabricator__CategoryAnchor" id={category.anchorKey}>
        {body}
      </div>
    );
  }

  return (
    <Section
      title={categoryTitle(category.title)}
      container_id={category.anchorKey}
      buttons={categoryButtons?.(category)}
    >
      {body}
    </Section>
  );
};
